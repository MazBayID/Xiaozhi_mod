#!/usr/bin/env python3
"""Generate the two tiny 1-bit Dirgamochi frames used by the Huy Vector C3 OLED.

Only the neutral pose (mochi_0, first frame) and the documented closed-eye
pose (mochi_2, source frame 009) are compiled into firmware. The original ZIPs
remain the editable source assets in the board directory.
"""
from __future__ import annotations

import io
import re
import zipfile
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
FACES = ROOT / "main/boards/huy-vector-c3/assets/faces"
BOARD = ROOT / "main/boards/huy-vector-c3"
WIDTH = 98
HEIGHT = 64
ROW_BYTES = (WIDTH + 7) // 8
FRAME_BYTES = ROW_BYTES * HEIGHT


def sort_key(name: str) -> int:
    match = re.match(r"(\d+)_", Path(name).name)
    return int(match.group(1)) if match else 0


def load_frame(zip_name: str, source_index: int) -> bytes:
    path = FACES / zip_name
    if not path.is_file():
        raise FileNotFoundError(f"Required face asset is missing: {path}")
    with zipfile.ZipFile(path) as archive:
        names = sorted(
            (name for name in archive.namelist() if name.lower().endswith(".png")),
            key=sort_key,
        )
        if len(names) <= source_index:
            raise RuntimeError(
                f"{zip_name} has {len(names)} PNG frames; "
                f"frame index {source_index} is unavailable"
            )
        with Image.open(io.BytesIO(archive.read(names[source_index]))) as source:
            image = source.convert("L")
            if image.size != (WIDTH, HEIGHT):
                image = image.resize((WIDTH, HEIGHT), Image.Resampling.LANCZOS)
            image = image.convert("1")
            pixels = image.load()

            packed = bytearray(FRAME_BYTES)
            for y in range(HEIGHT):
                row = y * ROW_BYTES
                for x in range(WIDTH):
                    if pixels[x, y]:
                        packed[row + (x >> 3)] |= 0x80 >> (x & 7)

    print(f"{zip_name}: selected {names[source_index]} -> {len(packed)} bytes")
    return bytes(packed)


def emit_array(symbol: str, data: bytes) -> str:
    lines = [f"const uint8_t {symbol}[{len(data)}] = {{"]
    for offset in range(0, len(data), 16):
        lines.append("    " + ", ".join(f"0x{value:02X}" for value in data[offset:offset + 16]) + ",")
    lines.append("};")
    return "\n".join(lines)


def main() -> None:
    idle = load_frame("mochi_0.zip", 0)
    blink = load_frame("mochi_2.zip", 8)

    header = BOARD / "mochi_face_frames.h"
    source = BOARD / "mochi_face_frames.cc"
    header.write_text(
        "// Generated by scripts/generate_mochi_frames.py; do not edit.\n"
        "#pragma once\n#include <cstdint>\n\n"
        f"constexpr int MOCHI_FACE_WIDTH = {WIDTH};\n"
        f"constexpr int MOCHI_FACE_HEIGHT = {HEIGHT};\n"
        f"constexpr int MOCHI_FACE_ROW_BYTES = {ROW_BYTES};\n"
        f"constexpr int MOCHI_FACE_FRAME_BYTES = {FRAME_BYTES};\n"
        "extern const uint8_t kMochiIdleFrame[MOCHI_FACE_FRAME_BYTES];\n"
        "extern const uint8_t kMochiBlinkFrame[MOCHI_FACE_FRAME_BYTES];\n",
        encoding="utf-8",
    )
    source.write_text(
        "// Generated by scripts/generate_mochi_frames.py; do not edit.\n"
        '#include "mochi_face_frames.h"\n\n'
        + emit_array("kMochiIdleFrame", idle)
        + "\n\n"
        + emit_array("kMochiBlinkFrame", blink)
        + "\n",
        encoding="utf-8",
    )
    print(
        f"Generated {header.name} and {source.name}: "
        f"{len(idle) + len(blink)} bitmap bytes total"
    )


if __name__ == "__main__":
    main()
